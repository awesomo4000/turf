"""Generate the C representation of the shared JavaScript. Use --check in tests."""
import json
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1] / 'src/automation'
text = '// Generated by tools/automation-scripts.py. Edit the .js sources.\n'
for name in ('evaluate', 'diagnostics', 'screenshot'):
    text += 'static const char turf_' + name + '_script[] =\n'
    text += '\n'.join(json.dumps(line + '\n') for line in (root / (name + '.js')).read_text().splitlines()) + ';\n'
path = root / 'scripts.h'
if '--check' in sys.argv:
    assert path.read_text() == text, 'Run tools/automation-scripts.py'
else:
    path.write_text(text)
